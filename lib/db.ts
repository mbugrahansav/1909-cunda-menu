import { Pool, type PoolClient } from "pg";
import fs from "node:fs/promises";
import path from "node:path";
import type { Category, Product } from "./types";

declare global {
  // eslint-disable-next-line no-var
  var postgresPool: Pool | undefined;
  // eslint-disable-next-line no-var
  var databaseReady: Promise<void> | undefined;
}

function getPool() {
  if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL ortam değişkeni tanımlı değil.");
  if (!global.postgresPool) {
    global.postgresPool = new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.POSTGRES_SSL === "true" ? { rejectUnauthorized: false } : undefined,
      max: 10,
    });
  }
  return global.postgresPool;
}

function cleanHtml(value: string) {
  return value.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").trim();
}

async function seedFromLegacyMenu(client: PoolClient) {
  // Advisory lock prevents two fresh application instances seeding simultaneously.
  await client.query("SELECT pg_advisory_xact_lock($1)", [1909]);
  const count = await client.query<{ count: string }>("SELECT COUNT(*) AS count FROM categories");
  if (Number(count.rows[0].count) > 0) return;
  const legacyPath = path.join(process.cwd(), "index.html");
  let html: string;
  try { html = await fs.readFile(legacyPath, "utf8"); } catch { return; }
  const sections = [...html.matchAll(/<div class="section">([\s\S]*?)(?=<div class="section">|<\/body>)/g)];
  for (const [categoryIndex, section] of sections.entries()) {
    const title = section[1].match(/<h1>(.*?)<\/h1>/)?.[1];
    if (!title) continue;
    const category = await client.query<{ id: number }>("INSERT INTO categories (name, sort_order) VALUES ($1, $2) RETURNING id", [cleanHtml(title), categoryIndex]);
    const items = [...section[1].matchAll(/<div class="menu-item">([\s\S]*?)(?=<div class="menu-item">|<\/div>\s*<\/div>\s*(?:<!--|<\/body>|$))/g)];
    for (const [itemIndex, item] of items.entries()) {
      const name = item[1].match(/item-name">([\s\S]*?)<\/span>/)?.[1];
      const price = item[1].match(/item-price">\s*([\d.,]+)/)?.[1];
      if (!name || !price) continue;
      const description = item[1].match(/item-description">([\s\S]*?)<\/div>/)?.[1] ?? "";
      await client.query(`INSERT INTO products (category_id, name, description, price, sort_order)
        VALUES ($1, $2, $3, $4, $5)`, [category.rows[0].id, cleanHtml(name), cleanHtml(description), Number(price.replace(/\D/g, "")), itemIndex]);
    }
  }
}

async function initializeDatabase() {
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    await client.query(`
      CREATE TABLE IF NOT EXISTS categories (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        sort_order INTEGER NOT NULL DEFAULT 0
      );
      CREATE TABLE IF NOT EXISTS products (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        price INTEGER NOT NULL CHECK(price >= 0),
        is_visible BOOLEAN NOT NULL DEFAULT TRUE,
        is_available BOOLEAN NOT NULL DEFAULT TRUE,
        sort_order INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS products_category_order_idx ON products(category_id, sort_order);
    `);
    await seedFromLegacyMenu(client);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally { client.release(); }
}

async function ready() {
  if (!global.databaseReady) global.databaseReady = initializeDatabase();
  return global.databaseReady;
}

type ProductRow = Omit<Product, "categoryId" | "isVisible" | "isAvailable" | "sortOrder"> & {
  category_id: number; is_visible: boolean; is_available: boolean; sort_order: number;
};

export async function getCategories(includeHidden = false): Promise<Category[]> {
  await ready();
  const [categoryResult, productResult] = await Promise.all([
    getPool().query<{ id: number; name: string; sort_order: number }>("SELECT id, name, sort_order FROM categories ORDER BY sort_order, id"),
    getPool().query<ProductRow>(`SELECT id, category_id, name, description, price, is_visible, is_available, sort_order
      FROM products ${includeHidden ? "" : "WHERE is_visible = TRUE"} ORDER BY sort_order, id`),
  ]);
  return categoryResult.rows.map((category) => ({
    id: category.id, name: category.name, sortOrder: category.sort_order,
    products: productResult.rows.filter((row) => row.category_id === category.id).map((row) => ({
      id: row.id, categoryId: row.category_id, name: row.name, description: row.description,
      price: row.price, isVisible: row.is_visible, isAvailable: row.is_available, sortOrder: row.sort_order,
    })),
  })).filter((category) => includeHidden || category.products.length > 0);
}

export async function createProduct(data: { categoryId: number; name: string; description: string; price: number }) {
  await ready();
  await getPool().query(`INSERT INTO products (category_id, name, description, price, sort_order)
    SELECT $1, $2, $3, $4, COALESCE(MAX(sort_order), -1) + 1 FROM products WHERE category_id = $1`, [data.categoryId, data.name, data.description, data.price]);
}

export async function updateProduct(id: number, data: { name: string; description: string; price: number; categoryId: number }) {
  await ready();
  await getPool().query("UPDATE products SET name=$1, description=$2, price=$3, category_id=$4, updated_at=NOW() WHERE id=$5", [data.name, data.description, data.price, data.categoryId, id]);
}

export async function toggleProduct(id: number, field: "is_visible" | "is_available") {
  await ready();
  // field is allow-listed by the type and server action before interpolation.
  await getPool().query(`UPDATE products SET ${field} = NOT ${field}, updated_at = NOW() WHERE id = $1`, [id]);
}

export async function deleteProduct(id: number) { await ready(); await getPool().query("DELETE FROM products WHERE id = $1", [id]); }
export async function createCategory(name: string) {
  await ready();
  await getPool().query("INSERT INTO categories (name, sort_order) SELECT $1, COALESCE(MAX(sort_order), -1) + 1 FROM categories", [name]);
}
export async function deleteCategory(id: number) { await ready(); await getPool().query("DELETE FROM categories WHERE id = $1", [id]); }
